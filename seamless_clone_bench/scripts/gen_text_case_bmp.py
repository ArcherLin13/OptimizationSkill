def new_image(bgr):
    return [bgr[:] for _ in range(H)]


def fill_rect(img, x, y, w, h, color):
    for yy in range(max(0, y), min(H, y + h)):
        for xx in range(max(0, x), min(W, x + w)):
            img[yy][xx] = color


def draw_text(img, x, y, text, color, scale=2):
    cx = x
    for ch in text.upper():
        glyph = FONT_5X7.get(ch, FONT_5X7[" "])
        for row in glyph:
            for col, bit in enumerate(row):
                if bit == "#":
                    fill_rect(img, cx + col * scale, y + row * scale, scale, scale, color)
            cx += 6 * scale
        cx += 2 * scale


def write_bmp(path, img):
    row_stride = ((W * 3 + 3) // 4) * 4
    pixel_bytes = row_stride * H
    header = struct.pack(
        "<2sIHHI",
        b"BM",
        54 + pixel_bytes,
        0,
        0,
        54,
    )
    info = struct.pack(
        "<IiiHHIIiiII",
        40,
        W,
        H,
        1,
        24,
        0,
        pixel_bytes,
        2835,
        2835,
        0,
        0,
    )
    with open(path, "wb") as f:
        f.write(header)
        f.write(info)
        pad = b"\x00" * (row_stride - W * 3)
        for y in range(H - 1, -1, -1):
            row = bytearray()
            for x in range(W):
                row.extend(img[y][x])
            f.write(row)
            f.write(pad)


def make_mask():
    img = [[0, 0, 0] for _ in range(H)]
    x, y, w, h = MASK_RECT
    fill_rect(img, x, y, w, h, (0, 220, 0))
    return img


def make_dst():
    img = new_image((90, 40, 25))
    draw_text(img, 16, 18, "BACKGROUND 729x126", (235, 235, 235), 2)
    draw_text(img, 16, 48, "DST: ABCD EFGH IJKL MNOP QRST", (220, 220, 220), 2)
    draw_text(img, 16, 78, "harmony seamless clone test", (200, 200, 120), 2)
    for x in range(20, W - 40, 54):
        draw_text(img, x, 100, "8gQy", (200, 200, 120), 1)
    return img


def make_src():
    img = new_image((210, 230, 255))
    draw_text(img, 16, 18, "SOURCE PATCH CLONE", (20, 20, 160), 2)
    draw_text(img, 16, 48, "SRC: 0123456789 9876543210", (30, 30, 140), 2)
    draw_text(img, 16, 78, "glyph edge sharpness check", (40, 40, 120), 2)
    for x in range(20, W - 40, 54):
        draw_text(img, x, 100, "6pZj", (180, 60, 20), 1)
    return img


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "samples" / "text_case")
    out.mkdir(parents=True, exist_ok=True)
    write_bmp(out / "src.bmp", make_src())
    write_bmp(out / "dst.bmp", make_dst())
    write_bmp(out / "mask.bmp", make_mask())
    (out / "center.txt").write_text(f"{CENTER[0]},{CENTER[1]}\n", encoding="ascii")
    print(f"Wrote text case BMPs to: {out}")
    print("  src.bmp dst.bmp mask.bmp center.txt")


if __name__ == "__main__":
    main()
